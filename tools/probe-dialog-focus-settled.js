/* Does the caret stay inside an open dialog after the app settles, or only in the breath after the
   click? Found on a handset, not on the bench.

   Walk 8 opened the resident hub's "Log out?" confirm on the vivo 1906 and read `document.activeElement`
   as `<body>` with `document.hasFocus()` true — so not the §89 blindness, and not TalkBack: the same
   reading held with the screen reader switched off and a single tap. The camera's dialog walk
   (`probe-layer-focus.js`) reported 9 of 9 carets inside, and `grep -i logout tools/shot.cjs` answers
   nothing: **the logout confirm is a dialog no walk visits**, so the two readings do not disagree — the
   bench never asked this surface.

   This probe asks it three ways per dialog: the moment after the click, one second later, and three
   seconds later. The reason for the waits is `focusIntoLayer`'s own signature guard — a dialog whose
   title id is regenerated by a later render can be re-labelled without being re-focused, and only a
   settled read distinguishes "moved then dropped" from "never moved". Run the same three reads on a
   dialog the walk *does* cover, so a failure here is about this surface and not about the method.

     node tools/shot.cjs --probe=@tools/probe-dialog-focus-settled.js --only=resident-profile
*/
(async () => {
  const read = () => {
    const t = [...document.querySelectorAll('[data-layer]')].pop();
    if (!t) return { layer: null };
    const box = t.querySelector('[role="dialog"]') || t.querySelector('.modal, .sheet, .card') || t;
    const id = box.getAttribute('aria-labelledby');
    return {
      layer: t.getAttribute('data-layer'), role: box.getAttribute('role'),
      name: id ? (((document.getElementById(id) || {}).textContent) || '').trim() : (box.getAttribute('aria-label') || null),
      inside: t.contains(document.activeElement), active: document.activeElement.tagName,
      hasFocus: document.hasFocus(),
    };
  };
  const wait = ms => new Promise(r => setTimeout(r, ms));
  const open = names => {
    const all = [...document.querySelectorAll('[onclick]')];
    for (const n of names) {
      const hit = all.find(e => (e.getAttribute('onclick') || '').indexOf(n) > -1
        && (!e.textContent || !/^\s*$/.test(e.textContent)));
      if (hit) { hit.click(); return hit; }
    }
    return null;
  };

  const CASES = [
    /* the hub row that opened the handset defect, then a dialog the camera does walk, as a control */
    { label: 'logout-confirm', openers: ["residentProfileAction('logout')"] },
    { label: 'edit-form', openers: ["residentProfileAction('edit')"] },
    /* Dropped after the first run reported `no painted opener`: the payment picker's button lives one
       tap deeper, inside the sheet that `payments` opens, so a single click cannot reach it from the hub.
       It is not a hole in coverage — `resident-payment-modal` is in the camera's table and the tally
       reaches it through the sheet — but a case that can never fire here would print a comfortable zero,
       which is the failure this file's whole design exists to avoid. */
  ];

  const out = [];
  for (const c of CASES) {
    /* close whatever is open first, the way the app's own Back does */
    if (typeof clearModals === 'function') clearModals();
    render(); await wait(400);
    const btn = open(c.openers);
    if (!btn) { out.push({ case: c.label, error: 'no painted opener' }); continue; }
    const t0 = read();
    await wait(1000); const t1 = read();
    await wait(2000); const t2 = read();
    out.push({ case: c.label, immediately: t0, at1s: t1, at3s: t2,
      caretLostAfterSettle: !!(t0.inside && !t2.inside), neverMoved: !(t2.inside || t1.inside || t0.inside) });
    if (typeof clearModals === 'function') { clearModals(); render(); await wait(300); }
  }

  const findings = out.filter(o => o.neverMoved || o.caretLostAfterSettle).length;
  return JSON.stringify({ screen: ((document.querySelector('#screen h1') || {}).textContent) || '?',
    findings, cases: out });
})()
